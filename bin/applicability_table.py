#!/usr/bin/env python3
"""Emit the excluded rows of the applicability grid, so the split can be checked.

The paper prints three counts: the grid's rows, how many are applicable, and how the
exclusions divide into "the tool's declared mechanisms do not intersect the pair's" and
"the mechanism fits but no harness was built here". Those two are different things and the
paper leans on the difference, because the first is a property of the tool and the second is
a property of this artifact's effort. A reader cannot check either from three numbers.

This generates the excluded rows from results/verdicts.jsonl, grouped by tool and reason, so
the counts reconcile on the page. It is generated rather than written, for the usual reason:
a hand-kept table of exclusions drifts the moment a harness is added.

Usage: bin/applicability_table.py [--out paper/tches/gen/applicability-table.tex]
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
from collections import defaultdict

REPO = pathlib.Path(__file__).resolve().parent.parent


def kind(reason: str) -> str:
    return "mechanism" if reason.startswith("mechanism:") else "harness"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(REPO / "paper" / "tches" / "gen" / "applicability-table.tex"))
    a = ap.parse_args()

    src = REPO / "results" / "verdicts.jsonl"
    rows = [json.loads(l) for l in src.read_text().splitlines() if l.strip()]
    excluded = [r for r in rows if not r.get("applicable")]

    grouped: dict[tuple[str, str], list[str]] = defaultdict(list)
    for r in excluded:
        grouped[(r["tool"], kind(r.get("reason", "")))].append(r["pair"])

    n_mech = sum(1 for r in excluded if kind(r.get("reason", "")) == "mechanism")
    n_harn = len(excluded) - n_mech

    lines = [
        "% GENERATED by bin/applicability_table.py. Do not hand-edit.",
        "\\begin{table}[h]",
        "\\centering\\footnotesize",
        "\\caption{The %d excluded rows of the %d-row applicability grid, so the split the "
        "paper leans on can be checked rather than taken on its counts. \\emph{Mechanism} is "
        "excluded by construction: the tool's declared mechanisms do not intersect the pair's, "
        "so the tool asserts no proposition about it and a miss would be meaningless. "
        "\\emph{No harness} is an effort boundary of this artifact, not a property of the tool: "
        "the mechanism fits and nothing was built. The two sum to %d mechanism and %d harness.}"
        % (len(excluded), len(rows), n_mech, n_harn),
        "\\label{tab:applicability}",
        "\\begin{tabular}{@{}llp{0.52\\linewidth}@{}}",
        "\\toprule",
        "Analyser & Excluded by & Pairs \\\\",
        "\\midrule",
    ]
    label = {"mechanism": "mechanism", "harness": "no harness"}
    for (tool, k) in sorted(grouped):
        pairs = ", ".join(sorted(grouped[(tool, k)])).replace("_", "\\_")
        lines.append(f"{tool} & {label[k]} & {pairs} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"applicability_table: wrote {out} "
          f"({len(excluded)} excluded rows: {n_mech} mechanism, {n_harn} harness)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
