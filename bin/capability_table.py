#!/usr/bin/env python3
"""Generate the per-tool capability table from data/tools.toml.

Applicability is computed from each tool's declared mechanisms; this table prints
those declarations so a reader can check every applicability cell against them
rather than taking the lattice on faith. Generated, not hand-typed, so it cannot
drift from the file the scorer actually reads. Writes paper/tches/gen/capability-table.tex.
"""
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "paper" / "tches" / "gen" / "capability-table.tex"

MECH = {
    "secret-branch": "branch",
    "variable-latency-op": "var-latency op",
    "address-data": "data address",
    "address-code": "code address",
}


def esc(s: str) -> str:
    return str(s).replace("&", r"\&").replace("_", r"\_").replace("#", r"\#").replace("%", r"\%")


def main() -> int:
    d = tomllib.loads((REPO / "data" / "tools.toml").read_text())
    tools = d.get("tool", {})
    L = [r"% GENERATED by bin/capability_table.py from data/tools.toml. Do not hand-edit.",
         r"\begin{table}[t]", r"\centering",
         r"\caption{What each analyser declares it can observe, from \texttt{data/tools.toml},"
         r" the same declarations the scorer intersects with each pair's mechanism to decide"
         r" applicability. \emph{Scored against} is the label the tool's own literature claims:"
         r" a timing test is scored for exploitability, an instruction-class or taint tool for"
         r" the constant-time policy. So the applicability of every cell in \Cref{tab:blindspot}"
         r" can be checked here rather than taken on faith.}",
         r"\label{tab:capability}", r"\small", r"\setlength{\tabcolsep}{5pt}",
         r"\begin{tabular}{@{}lll@{}}", r"\toprule",
         r"Analyser & Mechanisms detected & Scored against \\", r"\midrule"]
    for name in sorted(tools):
        t = tools[name]
        mechs = ", ".join(MECH.get(m, m) for m in t.get("detects_mechanisms", [])) or r"\NA"
        against = t.get("scored_against", r"\NA")
        L.append(f"\\texttt{{{esc(name)}}} & {esc(mechs)} & {esc(against)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"capability_table: wrote {OUT} ({len(tools)} tools)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
