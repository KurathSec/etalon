#!/usr/bin/env python3
"""Emit the corpus table (one row per corpus pair) from the manifests and the records.

WHY THIS EXISTS
The submission presented nine pairs as its instance count and reusable contribution
and named six of them in passing, none with its library, versions, identifier, class,
tier, provenance, recovery or certification. A referee could not tell what was built.
This table is read from pairs/*/pair.toml, the amplification constant in each pair's
source, and the recovery parameters the pipeline uses, so it cannot say more than the
manifests do.

Usage: corpus_table.py [--out paper/tches/gen/corpus-table.tex]
"""
from __future__ import annotations
import argparse
import json
import pathlib
import re
import sys
import tomllib

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT = REPO / "paper" / "tches" / "gen" / "corpus-table.tex"

# What certifies each patched arm, at the fix site, in the vocabulary of the
# closure table. Tier A: the arm the recovery fails on, certified by inspection at
# s (Section 6.1 names the evidence). Tier B: the patched arm is a modelled
# constant-time column of the observation dataset. Tier C: the patched arm is built
# and inspected but the pair enters no recall, so no closure row is claimed.
PATCHED = {
    "ecdsa-nonce": ("removed at $s$", "tail jump"),
    "ecdsa-address": ("removed at $s$", "tail jump"),
    "hmac-timing": ("removed", "constant-time compare"),
    "libgcrypt-minerva": ("relocated", "fix upstream of the primitive"),
    "minerva": ("modelled", ""),
    "tpmfail": ("modelled", ""),
    "kyberslash": ("removed", "no division-class instruction"),
    "hqc-reject": ("inspected", "no recall"),
    "ladderleak": ("inspected", "no recall"),
}
LIBRARY = {
    "ecdsa-nonce": "OpenSSL 1.0.1u primitives, written here",
    "ecdsa-address": "OpenSSL 1.0.1u primitives, written here",
    "hmac-timing": "HMAC tag compare, written here",
    "hqc-reject": "rejection sampler, written here",
    "ladderleak": "Montgomery ladder, written here",
    "libgcrypt-minerva": "libgcrypt 1.8.4 / 1.8.5 tarballs",
    "matrixssl-minerva": "MatrixSSL 4.2.1 / 4.3.0 / 4.6.0",
    "minerva": "libgcrypt, upstream observations",
    "tpmfail": "TPM, upstream observations",
    "kyberslash": "Kyber reference \\texttt{poly.c}",
}


def amp_constant(pair: pathlib.Path):
    for f in sorted((pair / "src").glob("*.c")):
        m = re.search(r"#define\s+AMP\s+(\d+)", f.read_text())
        if m:
            return int(m.group(1))
    return None


def identifier(prov: dict) -> str:
    adv = prov.get("advisory") or []
    if adv:
        return adv[0]
    doi = prov.get("doi") or []
    if doi:
        d = doi[0]
        m = re.search(r"tches\.v(\d{4})\.i(\d)", d)
        return f"TCHES {m.group(1)}({m.group(2)})" if m else d
    return "--"


def recovery(name: str, man: dict) -> str:
    rec = man.get("recovery", {})
    entry = rec.get("entry", "")
    if name == "hmac-timing":
        return "byte-by-byte forgery"
    if entry.startswith("recover/"):
        n = rec.get("ci_instance") or rec.get("full_instance")
        return f"lattice $d=90$, {n:,} sigs." if n else "lattice $d=90$"
    return "published exploit, not rerun"


def rows() -> list[dict]:
    out = []
    for p in sorted(REPO.glob("pairs/*/pair.toml")):
        man = tomllib.loads(p.read_text())
        pair = man.get("pair", {})
        if pair.get("role") != "corpus":
            continue
        name = p.parent.name
        cls = man.get("class", {})
        prov = man.get("provenance", {})
        tier = pair.get("tier", "?")
        amp = amp_constant(p.parent)
        closure, basis = PATCHED.get(name, ("--", ""))
        out.append({
            "pair": name, "tier": tier,
            "library": LIBRARY.get(name, prov.get("upstream_repo", "")),
            "id": identifier(prov),
            "class": f"{cls.get('observable','')}, {cls.get('secret_role','')}, {cls.get('origin','')}",
            "kind": prov.get("provenance_kind", ""),
            "recovery": recovery(name, man) + (f", $\\times${amp}" if amp and tier == "A" else ""),
            "patched": closure + (f" ({basis})" if basis else ""),
            "runtime": (man.get("recovery", {}).get("runtime") or "--"),
        })
    return out


def render(rs: list[dict]) -> str:
    kind_word = {"synthetic-reproduction": "reproduction", "vendored-reproduction": "vendored reproduction",
                 "release-pair": "release pair", "observation-dataset": "observation dataset"}
    lines = [
        "% generated by bin/corpus_table.py from pairs/*/pair.toml (role = corpus), the AMP",
        "% constant in each pair's source, and the recovery parameters; do not edit by hand.",
        "\\begin{table}[t]",
        "\\centering\\scriptsize",
        "\\caption{The corpus, one row per pair, from the manifests: class as (observable, secret,",
        "  origin); recovery with its lattice dimension, budget and, for a tier-A arm, the",
        "  amplification constant compiled in, then where it reruns (pure: stock interpreter;",
        "  image: pinned); the patched arm's closure row at $s$ and its evidence (\\Cref{sec:method}).}",
        "\\label{tab:corpus}",
        "\\setlength{\\tabcolsep}{2pt}\\renewcommand{\\arraystretch}{0.85}",
        "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{0.10\\linewidth}>{\\raggedright\\arraybackslash}p{0.21\\linewidth}>{\\raggedright\\arraybackslash}p{0.135\\linewidth}>{\\raggedright\\arraybackslash}p{0.12\\linewidth}>{\\raggedright\\arraybackslash}p{0.19\\linewidth}>{\\raggedright\\arraybackslash}p{0.165\\linewidth}@{}}",
        "\\toprule",
        "Pair & Library, arms, identifier & Class & Tier, kind & Recovery, verify & Patched arm \\\\",
        "\\midrule",
    ]
    for r in rs:
        kind = kind_word.get(r["kind"], r["kind"])
        lines.append(f"{r['pair']} & {r['library']}; {r['id']} & {r['class']} & "
                     f"{r['tier']}, {kind} & {r['recovery']}; {r['runtime']} & {r['patched']} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    rs = rows()
    pathlib.Path(a.out).write_text(render(rs))
    print(f"corpus_table: wrote {a.out} ({len(rs)} pairs)")
    for r in rs:
        print(f"  {r['pair']:<18} {r['tier']} {r['kind']:<24} {r['recovery']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
