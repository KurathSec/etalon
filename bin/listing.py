#!/usr/bin/env python3
"""Emit the KyberSlash division listing from the committed pair source.

The paper's first claim is about four lines of C: the identical source emits a
hardware division in two of eight pinned build cells and a constant-time
reciprocal multiply in the other six. It never showed those lines. A paper that
argues about emitted instructions and prints no code asks the reader to take the
premise on trust.

The listing is generated rather than transcribed for the same reason every number
here is: a transcribed listing is prose, and prose drifts from the artifact it
describes. This reads pairs/kyberslash/src/{vulnerable,patched}.c, which are the
files the corpus actually builds and scores, and emits both arms side by side.
"""
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SRC = REPO / "pairs" / "kyberslash" / "src"
OUT = REPO / "paper" / "tches" / "gen" / "listing-division.tex"

FUNC = re.compile(r"^uint16_t coeff_to_bit\(uint16_t t\)\n\{\n(.*?)^\}", re.M | re.S)


def body(arm: str) -> list[str]:
    src = (SRC / f"{arm}.c").read_text()
    m = FUNC.search(src)
    if not m:
        sys.exit(f"listing: no coeff_to_bit body in {arm}.c")
    lines = ["uint16_t coeff_to_bit(uint16_t t)", "{"]
    lines += [ln.rstrip() for ln in m.group(1).rstrip().splitlines()]
    lines.append("}")
    return lines


def code_only(lines: list[str]) -> str:
    """The lines with C comments removed.

    The guard below asks whether the arm divides, and the patched arm's comment
    explains which division its reciprocal replaces. Checking the raw text finds
    that comment and refuses to build a listing that is correct. Strip first.
    """
    return re.sub(r"/\*.*?\*/", "", "\n".join(lines), flags=re.S)


def main() -> int:
    vuln, patched = body("vulnerable"), body("patched")
    if "/ KYBER_Q" not in code_only(vuln).replace("/KYBER_Q", "/ KYBER_Q"):
        sys.exit("listing: the vulnerable arm no longer divides by KYBER_Q; the "
                 "listing would no longer show what the paper says it shows")
    if "/ KYBER_Q" in code_only(patched).replace("/KYBER_Q", "/ KYBER_Q"):
        sys.exit("listing: the patched arm still divides by KYBER_Q")

    def block(lines):
        # Trailing block comments are elided from the rendering: the two arms sit
        # side by side in half a text width, and a comment pushes the one line the
        # figure exists to show across the column boundary. The caption says what
        # the elided comments say. The guard above still reads the full source.
        shown = [re.sub(r"\s*/\*.*?\*/\s*$", "", ln) for ln in lines]
        return "\\begin{verbatim}\n" + "\n".join(shown) + "\n\\end{verbatim}"

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "% GENERATED by bin/listing.py from pairs/kyberslash/src/. Do not hand-edit.\n"
        "\\begin{figure}[t]\n\\centering\\scriptsize\n"
        "\\begin{minipage}[t]{0.48\\linewidth}\n"
        "\\centering\\textbf{vulnerable arm}\\\\[2pt]\n" + block(vuln) + "\n"
        "\\end{minipage}\\hfill\n"
        "\\begin{minipage}[t]{0.48\\linewidth}\n"
        "\\centering\\textbf{patched arm}\\\\[2pt]\n" + block(patched) + "\n"
        "\\end{minipage}\n"
        "\\caption{The whole of the leak, from \\texttt{pairs/kyberslash/src/}; the two arms "
        "differ in one line. \\texttt{KYBER\\_Q} is \\ksModulus{}, not a power of two, so "
        "whether the division on the left becomes a hardware divide or a reciprocal multiply "
        "is the compiler's decision: one in \\nLeakingCells{} of \\nEmissionCells{} pinned "
        "build cells, the other in \\nConstantTimeCells{} (\\Cref{fig:emission}). The "
        "right-hand arm is the upstream fix and emits no division in any cell; neither arm "
        "contains a branch or a secret-indexed load. The source's own comments are elided; "
        "they mark the division as secret-dependent and the "
        "replacement as an exact floor.}\n"
        "\\label{lst:division}\n\\end{figure}\n")
    print(f"listing: wrote {OUT} ({len(vuln)} + {len(patched)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
