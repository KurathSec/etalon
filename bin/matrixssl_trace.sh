#!/bin/sh
# Regenerate the MatrixSSL signing trace AND retain its key.
#
# An earlier revision of the paper marked three groups of numbers as not recomputable
# from committed samples, and the largest was this one: the end-to-end analysis rested
# on a signing trace and a private key that were never retained. Nothing about
# disclosure prevented committing them, since both came from a keypair we generated;
# they were simply lost with the temporary tree the acquisition built into. This script
# is why that is no longer so: the trace and key it writes are committed under
# pairs/matrixssl-minerva/evidence/, and no printed quantity is non-recomputable now.
#
# Size is a real constraint. The trace the paper cites is a quarter of a million
# signatures, which compresses to roughly twenty megabytes, against a repository whose
# largest committed artifact is three. This writes a smaller trace by default. The
# information measure the analysis rests on is budget-robust, and the committed record
# already shows it reading the same at six thousand signatures as at two hundred and
# fifty thousand, so a smaller committed trace supports the same estimate. What it
# does NOT support is a recovery-budget claim at the larger number, and the paper has
# to say the budget it can show rather than the budget it once ran.
#
# Usage: matrixssl_trace.sh <work-dir-from-matrixssl_rebuild> [nsigs] [version]
set -eu
REPO="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${1:?usage: matrixssl_trace.sh <work-dir> [nsigs] [version]}"
NSIGS="${2:-25000}"
VER="${3:-4-3-0}"
CORE="${CORE:-3}"
M="matrixssl-$VER-open"
OUT="$REPO/pairs/matrixssl-minerva/evidence"
[ -d "$WORK/build/$M" ] || { echo "no build for $VER; run bin/matrixssl_rebuild.sh" >&2; exit 1; }

TMP="$WORK/trace-tmp"; mkdir -p "$TMP"
podman run --rm --network=none -v "$WORK/build:/w:Z" -v "$REPO/pairs/matrixssl-minerva/acquire:/a:ro,Z" \
  -v "$TMP:/t:Z" localhost/ct-toolchain/gcc-bookworm:1 sh -c \
  "cd /w && gcc -O2 -DNSIGS=$NSIGS -I$M -I$M/crypto -I$M/core/include \
     -I$M/core/osdep/include -I$M/core /a/sign_mx.c $M/crypto/libcrypt_s.a \
     $M/core/libcore_s.a -lm -o /t/sign && taskset -c $CORE /t/sign > /t/trace.csv 2>/t/priv.txt"

lines=$(wc -l < "$TMP/trace.csv")
want=$((NSIGS + 1))
[ "$lines" -eq "$want" ] || { echo "trace has $lines lines, expected $want" >&2; exit 1; }
grep -q '^PRIV [0-9a-f]\{64\}$' "$TMP/priv.txt" || { echo "no private key captured" >&2; exit 1; }

python3 -c "
import zlib, pathlib, sys
raw = pathlib.Path('$TMP/trace.csv').read_bytes()
pathlib.Path('$OUT/trace-$VER.csv.z').write_bytes(zlib.compress(raw, 9))
print(f'  trace-$VER.csv.z: {len(raw)/1e6:.1f} MB raw -> {pathlib.Path(\"$OUT/trace-$VER.csv.z\").stat().st_size/1e6:.1f} MB')
"
sed -n 's/^PRIV //p' "$TMP/priv.txt" > "$OUT/signing-key-$VER.hex"
echo "matrixssl_trace: $NSIGS signatures and the signing key retained under $OUT"
echo "  the key is for a keypair generated by this script; it signs nothing outside it"
