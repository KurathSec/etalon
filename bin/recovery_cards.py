#!/usr/bin/env python3
"""Generate the per-pair recovery cards and the divergence table.

W7: a reviewer of a key-recovery corpus wants to see the recovery, not take it on
faith. Roughly seventy percent of the card is already structured data in the pair
manifests and the vendored attack's params.json; this assembles it, so every field
in the paper table is regenerated from committed data rather than typed. Emits a
LaTeX table file the paper inputs; no new measurement is taken here.

    bin/recovery_cards.py            # write paper/tches/gen/recovery-cards.tex
    bin/recovery_cards.py --print    # to stdout
"""
from __future__ import annotations

import argparse
import json
import re
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "paper" / "tches" / "gen" / "recovery-cards.tex"


def tex_escape(s: str) -> str:
    return (str(s).replace("\\", r"\textbackslash{}").replace("_", r"\_")
            .replace("&", r"\&").replace("%", r"\%").replace("#", r"\#"))


def _abbr(v: str) -> str:
    return {"recovered": "rec.", "not-recovered": "none"}.get(v, tex_escape(v))


def amp_factor(pair_dir: Path):
    v = pair_dir / "src" / "vulnerable.c"
    if v.exists():
        m = re.search(r"#define\s+AMP\s+(\d+)", v.read_text())
        if m:
            return m.group(1)
        m = re.search(r"(\d+)\s*\*\s*bits", v.read_text())
        if m:
            return m.group(1)
    # Some pairs amplify in a separate per-byte work unit rather than in
    # vulnerable.c (e.g. hmac-timing's byte_work loop), so read that too. The loop
    # bound is the per-byte amplification factor over a single deployed compare.
    w = pair_dir / "src" / "work.c"
    if w.exists():
        m = re.search(r"for\s*\(\s*int\s+i\s*=\s*0;\s*i\s*<\s*(\d+);", w.read_text())
        if m:
            return m.group(1)
    return None


def card(pair_dir: Path) -> dict | None:
    man = tomllib.loads((pair_dir / "pair.toml").read_text())
    if man["pair"].get("role") != "corpus" or man["pair"].get("tier") not in ("A", "B"):
        return None
    prov = man.get("provenance", {})
    rec = man.get("recovery", {})
    acq = man.get("acquisition", {})
    orc = man.get("oracle", {})
    params = {}
    pj = pair_dir / "vendor" / "attack" / "params.json"
    if pj.exists():
        params = json.loads(pj.read_text())
    return {
        "pair": pair_dir.name,
        "tier": man["pair"].get("tier"),
        "cve": ", ".join(prov.get("advisory", []) or ["--"]),
        "doi": ", ".join(prov.get("doi", []) or ["--"]),
        "sigs": acq.get("sigs") or rec.get("full_instance") or "--",
        "library": ("fpylll" if "dimension" in params else
                    (rec.get("vendored_attack", "--").split(",")[0] or "--")),
        "lattice_dim": params.get("dimension", "--"),
        "bkz": (f"{min(params['betas'])}--{max(params['betas'])}"
                if params.get("betas") else "--"),
        "amp": amp_factor(pair_dir) or "1",
        "predicate": orc.get("predicate", "--"),
        "expect_v": orc.get("expected_vulnerable", "--"),
        "expect_p": orc.get("expected_patched", "--"),
        "divergence": man.get("divergence", {}).get("structured", []),
    }


def render(cards: list[dict]) -> str:
    L = [r"% GENERATED by bin/recovery_cards.py. Do not hand-edit.",
         r"\begin{table}[t]", r"\centering",
         r"\caption{Recovery card per recall-eligible pair, assembled from the committed"
         r" manifests and the vendored attack's parameters. The recovery verifies from"
         r" committed observations under the published key (controls ORC-1/2); the"
         r" amplification factor is the disclosed divergence from the deployed original,"
         r" read from the pair's driver.}",
         r"\label{tab:recovery}", r"\footnotesize", r"\setlength{\tabcolsep}{3pt}",
         r"\begin{tabular}{@{}llllrrl@{}}", r"\toprule",
         r"Pair & Tier & Advisory & Recovery & $n_{\mathrm{sig}}$ & Amp. & Oracle \\",
         r"\midrule"]
    for c in cards:
        recov = (f"lattice, dim\\,{c['lattice_dim']}, BKZ\\,{c['bkz']}"
                 if c["lattice_dim"] != "--" else "direct")
        L.append(f"{tex_escape(c['pair'])} & {c['tier']} & {tex_escape(c['cve'])} & "
                 f"{recov} & {c['sigs']} & {tex_escape(c['amp'])}$\\times$ & "
                 f"{_abbr(c['expect_v'])}/{_abbr(c['expect_p'])} \\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    # Divergence table
    L += [r"\begin{table}[t]", r"\centering",
          r"\caption{Divergence of each reproduction from its deployed original, per pair"
          r" and axis, so the ``reproduced leaks are not wild leaks'' caveat is tabulated"
          r" rather than asserted once.}",
          r"\label{tab:divergence}", r"\small", r"\setlength{\tabcolsep}{4pt}",
          r"\begin{tabular}{@{}lp{0.18\linewidth}p{0.28\linewidth}p{0.30\linewidth}@{}}",
          r"\toprule", r"Pair & Axis & Reproduced & Effect \\", r"\midrule"]
    any_div = False
    for c in cards:
        for d in c["divergence"]:
            any_div = True
            L.append(f"{tex_escape(c['pair'])} & {tex_escape(d.get('axis',''))} & "
                     f"{tex_escape(d.get('reproduced',''))} & {tex_escape(d.get('effect',''))} \\\\")
    if not any_div:
        L.append(r"\multicolumn{4}{c}{\NA} \\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true")
    a = ap.parse_args()
    cards = [c for c in (card(p.parent) for p
                         in sorted((REPO / "pairs").glob("*/pair.toml"))) if c]
    text = render(cards)
    if a.print:
        print(text)
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text)
        print(f"recovery_cards: wrote {OUT} ({len(cards)} cards)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
