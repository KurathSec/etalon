#!/usr/bin/env python3
"""Emit the fix-survey triage table from results/fix_verification.json.

The paper reports three deployed remediations of one leak. A reader's first
question is why three, and the honest answer has been sitting in a results file:
five candidates were examined, three were built and measured, and the other two
have a recorded reason. Printing only the three makes a survey look like a
convenience sample; printing all five with their reasons makes it a funnel.

This is the arrangement the Minerva paper used for the same problem. Its Table 1
lists all eighteen implementations tested, including the twelve that did not
leak, and that table rather than the attack is what makes the paper's coverage
legible. The rows that carry weight here are the two that are not results.
"""
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
FV = REPO / "results" / "fix_verification.json"
OUT = REPO / "paper" / "tches" / "gen" / "survey-table.tex"


def esc(s: str) -> str:
    for a, b in (("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#")):
        s = s.replace(a, b)
    return s


def main() -> int:
    doc = json.loads(FV.read_text())
    tri = doc["survey_triage"]
    cands = tri["candidates"]

    rows = []
    for name, c in cands.items():
        m = re.match(r"^(.*?)\s*(CVE-[\d-]+)?\s*(\([^)]*\))?$", name.strip())
        lib = (m.group(1) or name).strip()
        cve = m.group(2) or ""
        built, measured = bool(c.get("built")), bool(c.get("measured"))
        if measured and c.get("class_confirmed") is False:
            outcome = esc(str(c.get("class_predicted_from_source", ""))) + ", not confirmed"
        elif measured:
            outcome = esc(str(c.get("class", "")))
        elif c.get("not_built_reason"):
            outcome = "triaged, not built"
        else:
            outcome = "not triaged"
        why = c.get("not_built_reason") or c.get("triage", "")
        rows.append((esc(lib), esc(cve), outcome,
                     "yes" if built else "no", "yes" if measured else "no", why))

    n_measured = sum(1 for r in rows if r[4] == "yes")
    if n_measured != 3:
        sys.exit(f"survey_table: {n_measured} measured candidates, the paper says three")

    body = "\n".join(
        f"{lib} & {cve or '--'} & {outcome} & {b} & {m} \\\\" for lib, cve, outcome, b, m, _ in rows)

    # The two unmeasured rows carry the coverage argument, so their reasons are printed
    # rather than left in the results file. Compressed to one clause each by hand would
    # be prose; taken from the record they cannot drift from it.
    notes = []
    for lib, _cve, _o, b, _m, why in rows:
        if b == "no" and why:
            first = why.split(". ")[0].rstrip(".")
            notes.append(f"\\emph{{{lib}}}: {esc(first)}.")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "% GENERATED by bin/survey_table.py from results/fix_verification.json. Do not hand-edit.\n"
        "\\begin{table}[!ht]\n\\centering\\small\n"
        "\\caption{Every deployed remediation of this leak that was examined, not only the "
        "ones that yielded a measurement. Triage reads the fix commit and classifies it from "
        "source before any build, which costs minutes where a build-and-acquire cycle costs "
        "hours; only candidates whose diff predicts a discriminating pair are then built. "
        + " ".join(notes) +
        " The Crypto++ fix is a fourth strategy, branch-free selection by multiplication on a "
        "bignum layer that is itself variable time in operand size, which is the same "
        "substrate trap the MatrixSSL case identifies; it is classified and not measured.}\n"
        "\\label{tab:survey}\n"
        "\\begin{tabular}{@{}llllc@{}}\n\\toprule\n"
        "Library & Advisory & Triage outcome & Built & Measured \\\\\n\\midrule\n"
        + body + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print(f"survey_table: wrote {OUT} ({len(rows)} candidates, {n_measured} measured)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
